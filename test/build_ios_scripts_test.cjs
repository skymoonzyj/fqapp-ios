// Archive strips the linked executable after dSYM generation. FRB looks up
// global symbols at runtime, so Runner must retain them outside the script too.
for (const configuration of ['Release', 'Profile']) {
  test(`Runner ${configuration} archive preserves runtime FRB global symbols`, () => {
    const project = fs.readFileSync(path.join(source, 'ios/Runner.xcodeproj/project.pbxproj'), 'utf8');
    const objects = new Map([...project.matchAll(/^\t\t([A-F0-9]{24}) \/\* [^\n]+ \*\/ = \{\n([\s\S]*?)^\t\t\};/gm)]
      .map(match => [match[1], match[2]]));
    const runner = [...objects.values()].find(body => /isa = PBXNativeTarget;/.test(body) && /\bname = Runner;/.test(body));
    assert.ok(runner, 'Runner application target must exist');
    const listId = runner.match(/buildConfigurationList = ([A-F0-9]{24})/)[1];
    const configurationIds = [...objects.get(listId).matchAll(/([A-F0-9]{24}) \/\*/g)].map(match => match[1]);
    const settings = configurationIds.map(id => objects.get(id)).find(body => body.includes(`name = ${configuration};`));
    assert.ok(settings, `Runner ${configuration} configuration must exist`);
    assert.match(settings, /STRIP_STYLE = "non-global";/,
      'Archive must strip local symbols only; default all removes runtime FRB exports');
  });
}
